def is_valid(opcode):
    """Return True if opcode is valid, False otherwise."""
    return 0 <= opcode < _NUM_OPCODES and opcode in _FLAGS


def _has(opcode, flag):
    return is_valid(opcode) and bool(_FLAGS[opcode] & flag)


def has_arg(opcode):
    """Return True if the opcode uses its oparg, False otherwise."""
    return _has(opcode, HAS_ARG_FLAG)


def has_const(opcode):
    """Return True if the opcode accesses a constant, False otherwise."""
    return _has(opcode, HAS_CONST_FLAG)


def has_name(opcode):
    """Return True if the opcode accesses an attribute by name, False otherwise."""
    return _has(opcode, HAS_NAME_FLAG)


def has_jump(opcode):
    """Return True if the opcode has a jump target, False otherwise."""
    return _has(opcode, HAS_JUMP_FLAG)


def has_free(opcode):
    """Return True if the opcode accesses a free variable, False otherwise."""
    return _has(opcode, HAS_FREE_FLAG)


def has_local(opcode):
    """Return True if the opcode accesses a local variable, False otherwise."""
    return _has(opcode, HAS_LOCAL_FLAG)


def has_exc(opcode):
    """Return True if the opcode sets an exception handler, False otherwise."""
    return is_valid(opcode) and opcode in _BLOCK_PUSH


def stack_effect(opcode, oparg=None, /, *, jump=None):
    """Compute the stack effect of the opcode."""
    oparg_int = 0 if oparg is None else int(oparg)
    if jump is None:
        jump_int = -1
    elif jump is True:
        jump_int = 1
    elif jump is False:
        jump_int = 0
    else:
        raise ValueError("stack_effect: jump must be False, True or None")
    # `get_stack_effects` (Python/flowgraph.c): specialized forms and
    # unknown opcodes have no effect entry.
    if opcode < 0 or (opcode <= _MAX_REAL_OPCODE and _DEOPT.get(opcode, opcode) != opcode):
        raise ValueError("invalid opcode or oparg")
    popped = _POPPED.get(opcode)
    pushed = _PUSHED.get(opcode)
    if popped is None or pushed is None:
        raise ValueError("invalid opcode or oparg")
    npop = popped(oparg_int)
    npush = pushed(oparg_int)
    if npop < 0 or npush < 0:
        raise ValueError("invalid opcode or oparg")
    if opcode in _BLOCK_PUSH and not jump_int:
        return 0
    return npush - npop


