def is_valid(opcode):
    """Return True if opcode is valid, False otherwise."""
    return opcode in _VALID or (0 <= opcode < _NUM_OPCODES and opcode in _FLAGS)


def _has(opcode, flag):
    return is_valid(opcode) and bool(_FLAGS[opcode] & flag)


def has_arg(opcode):
    """Return True if the opcode uses its oparg, False otherwise."""
    if opcode in _HAS_ARG:
        return True
    if opcode in _VALID:
        return False
    # An invalid opcode, or not an int (which raises as before).
    return _has(opcode, HAS_ARG_FLAG)


